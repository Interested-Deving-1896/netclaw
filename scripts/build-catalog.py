#!/usr/bin/env python3
"""Generate the Bash 3.2 compatibility catalog from canonical JSON."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def quote(text):
    if any(c in text for c in ('\n', '\r', '\0', '|')):
        raise ValueError('Catalog field cannot contain shell delimiters')
    return text.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('`', '\\`')


def render(catalog):
    encoded = json.dumps(catalog, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode()
    lines = ['#!/usr/bin/env bash', '# Generated by scripts/build-catalog.py; edit config/components/catalog.json.',
             '# Catalog SHA-256: ' + hashlib.sha256(encoded).hexdigest(), '', 'CATALOG=(']
    for component in catalog['components']:
        lines.append('    "' + '|'.join(quote(component[k]) for k in ('id', 'category', 'title', 'description')) + '"')
    lines += [')', '', '''catalog_field() {
    local id="$1" n="$2" entry
    for entry in "${CATALOG[@]}"; do
        if [ "${entry%%|*}" = "$id" ]; then
            echo "$entry" | cut -d'|' -f"$n"
            return 0
        fi
    done
    return 1
}

catalog_ids() {
    local entry
    for entry in "${CATALOG[@]}"; do echo "${entry%%|*}"; done
}

catalog_has() {
    local id="$1" entry
    for entry in "${CATALOG[@]}"; do
        [ "${entry%%|*}" = "$id" ] && return 0
    done
    return 1
}
''']
    for profile in catalog['profiles']:
        if profile['id'] != 'full':
            lines.append('PROFILE_' + profile['id'].upper() + '="' + ' '.join(profile['components']) + '"')
    lines += ['', 'profile_components() {', '    case "$1" in']
    for profile in catalog['profiles']:
        name = profile['id']
        action = "catalog_ids | tr '\\n' ' '" if name == 'full' else 'echo "$PROFILE_' + name.upper() + '"'
        lines.append('        ' + name + ') ' + action + ' ;;')
    lines += ['        *) return 1 ;;', '    esac', '}', '', 'PROFILE_NAMES="' + ' '.join(p['id'] for p in catalog['profiles']) + '"', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'scripts/lib/catalog.sh'
    catalog = json.loads((ROOT / 'config/components/catalog.json').read_text())
    rendered = render(catalog)
    env_map = {a['surface']: {'env': a['fieldKeys'], 'files': a['files'], 'notes': a['reason']} for a in catalog['surfaceAliases']}
    # HUD deployments copy this module. Keep its catalog projection alongside the
    # HUD rather than requiring a second repository-relative JSON file at import.
    aliases = {a['surface']: a['components'] for a in catalog['surfaceAliases']}
    fields = {c['id']: c['settings'] for c in catalog['components']}
    env_rendered = '// Generated from config/components/catalog.json by scripts/build-catalog.py.\nexport const ENV_MAP = ' + json.dumps(env_map, indent=2, ensure_ascii=False) + ';\n'
    env_rendered += 'export const COMPONENT_ALIASES = ' + json.dumps(aliases, indent=2, ensure_ascii=False) + ';\n'
    env_rendered += 'export const COMPONENT_SETTINGS = ' + json.dumps(fields, indent=2, ensure_ascii=False) + ';\n'
    env_output = ROOT / 'ui/netclaw-visual/env-map.js'
    if args.check:
        if output.read_text() != rendered or env_output.read_text() != env_rendered:
            print('Generated catalog differs; run python3 scripts/build-catalog.py', file=sys.stderr)
            return 1
    else:
        output.write_text(rendered)
        env_output.write_text(env_rendered)
    print('Catalog generation parity: PASS')
    return 0


if __name__ == '__main__':
    sys.exit(main())
